"""Generate worlds/powerline.sdf from a mission file.

The mission YAML is the single source of truth for where things are: this
script places the landing pad and a simplified transmission tower at each
tower position, plus three conductors strung between consecutive towers.
It starts from worlds/landing_pad.sdf so physics, lighting and the geodetic
origin are identical in both worlds.

Mission positions are PX4 local NED (north, east); Gazebo's world is ENU, so
a tower at north N, east E goes to Gazebo x = E, y = N.

usage: python tools/gen_powerline_world.py missions/powerline.yaml worlds/powerline.sdf
"""
import math
import sys
from pathlib import Path

from vland.mission import Mission, Tower, load_mission

REPO = Path(__file__).resolve().parents[1]

CROSSARM_HALF = 2.5     # m: outer conductors hang this far either side
CONDUCTOR_DROP = 0.6    # m below the crossarm (insulator length)
PHASE_OFFSETS = (-CROSSARM_HALF, 0.0, CROSSARM_HALF)


def _box(name, pose, size, rgb):
    r, g, b = rgb
    return f"""
        <collision name="{name}_c"><pose>{pose}</pose><geometry><box><size>{size}</size></box></geometry></collision>
        <visual name="{name}"><pose>{pose}</pose><geometry><box><size>{size}</size></box></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material></visual>"""


def _cyl(name, pose, radius, length, rgb):
    r, g, b = rgb
    return f"""
        <visual name="{name}"><pose>{pose}</pose><geometry><cylinder><radius>{radius}</radius><length>{length}</length></cylinder></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material></visual>"""


def line_heading(m: Mission, i: int) -> float:
    """Direction of the line at tower i (ENU yaw, radians), so the crossarm
    can be placed perpendicular to it."""
    a = m.towers[max(i - 1, 0)]
    b = m.towers[min(i + 1, len(m.towers) - 1)]
    return math.atan2(b.north_m - a.north_m, b.east_m - a.east_m)


def tower_sdf(t: Tower, yaw_line: float) -> str:
    h = t.height_m
    steel = (0.55, 0.57, 0.6)
    glass = (0.35, 0.55, 0.75)
    # Model frame: x along the line, y across it (crossarm), z up.
    parts = [
        _box("pole", f"0 0 {h / 2} 0 0 0", f"0.7 0.7 {h}", steel),
        _box("crossarm", f"0 0 {h - 0.15} 0 0 0", f"0.3 {2 * CROSSARM_HALF + 0.6} 0.3", steel),
        _box("peak", f"0 0 {h + 0.6} 0 0 0", "0.3 0.3 1.2", steel),
    ]
    for k, y in enumerate(PHASE_OFFSETS):
        parts.append(_cyl(f"insulator_{k}", f"0 {y} {h - 0.3 - CONDUCTOR_DROP / 2} 0 0 0",
                          0.09, CONDUCTOR_DROP, glass))
    return f"""
    <model name="tower_{t.id}">
      <static>true</static>
      <pose>{t.east_m} {t.north_m} 0 0 0 {yaw_line}</pose>
      <link name="link">{''.join(parts)}
      </link>
    </model>"""


def conductors_sdf(m: Mission) -> str:
    visuals = []
    for i in range(len(m.towers) - 1):
        a, b = m.towers[i], m.towers[i + 1]
        yaw = math.atan2(b.north_m - a.north_m, b.east_m - a.east_m)
        length = math.hypot(b.north_m - a.north_m, b.east_m - a.east_m)
        z = (a.height_m + b.height_m) / 2 - 0.3 - CONDUCTOR_DROP
        for k, off in enumerate(PHASE_OFFSETS):
            # Offset perpendicular to the span, then lay a cylinder along it.
            cx = (a.east_m + b.east_m) / 2 - off * math.sin(yaw)
            cy = (a.north_m + b.north_m) / 2 + off * math.cos(yaw)
            # A cylinder's axis is z; pitch it 90 deg to lie along x, then yaw.
            visuals.append(_cyl(f"span{i}_phase{k}", f"{cx} {cy} {z} 0 1.5707963 {yaw}",
                                0.03, length, (0.15, 0.15, 0.15)))
    return f"""
    <model name="conductors">
      <static>true</static>
      <link name="link">{''.join(visuals)}
      </link>
    </model>"""


def generate(m: Mission, template: str) -> str:
    world = template.replace('<world name="landing_pad">', '<world name="powerline">')
    pad_pose = "<pose>3 2 0 0 0 0</pose>"
    assert pad_pose in world, "landing_pad.sdf changed: update the pad pose in this generator"
    world = world.replace(pad_pose, f"<pose>{m.pad.east_m} {m.pad.north_m} 0 0 0 0</pose>")
    models = "".join(tower_sdf(t, line_heading(m, i)) for i, t in enumerate(m.towers)) + conductors_sdf(m)
    header = ("<!-- GENERATED by tools/gen_powerline_world.py from the mission file. "
              "Edit the mission YAML and regenerate rather than editing this file. -->\n")
    world = world.replace("<sdf version", header + "<sdf version", 1)
    return world.replace("  </world>", models + "\n  </world>", 1)


if __name__ == "__main__":
    mission_path = sys.argv[1] if len(sys.argv) > 1 else REPO / "missions" / "powerline.yaml"
    out_path = sys.argv[2] if len(sys.argv) > 2 else REPO / "worlds" / "powerline.sdf"
    template = (REPO / "worlds" / "landing_pad.sdf").read_text()
    Path(out_path).write_text(generate(load_mission(mission_path), template))
    print("wrote", out_path)
